/**
 * Generates supabase/seed.sql from data/questions.seed.json.
 *   npm run seed:build
 * The SQL is idempotent (keyed by seed_key) and imports every translation as
 * NOT reviewed, so nothing can be scheduled until an admin has checked it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface SeedQuestion {
  key: string;
  [locale: string]: string;
}

const root = join(__dirname, '..');
const data = JSON.parse(readFileSync(join(root, 'data', 'questions.seed.json'), 'utf8')) as {
  questions: SeedQuestion[];
};

const LOCALES = ['en', 'et', 'es'];
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

const errors: string[] = [];
const keys = new Set<string>();
for (const q of data.questions) {
  if (!/^[a-z0-9-]+$/.test(q.key)) errors.push(`bad key: ${q.key}`);
  if (keys.has(q.key)) errors.push(`duplicate key: ${q.key}`);
  keys.add(q.key);
  for (const l of LOCALES) {
    const t = q[l];
    if (!t) errors.push(`${q.key}: missing ${l}`);
    else if (t.length > 200) errors.push(`${q.key}: ${l} longer than 200 chars`);
    else if (!t.trim().endsWith('?')) errors.push(`${q.key}: ${l} must end with "?"`);
  }
  if (q.es && !q.es.startsWith('¿')) errors.push(`${q.key}: es must start with "¿"`);
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

let sql = `-- GENERATED by scripts/build-seed.ts from data/questions.seed.json. Do not edit by hand.
-- ${data.questions.length} questions. All translations start as reviewed = false.

`;
for (const q of data.questions) {
  sql += `with q as (
  insert into public.questions (status, source, seed_key) values ('draft', 'seed', ${lit(q.key)})
  on conflict (seed_key) do update set seed_key = excluded.seed_key
  returning id
)
insert into public.question_translations (question_id, locale, text, reviewed)
select q.id, v.locale, v.text, false from q, (values
${LOCALES.map((l) => `  (${lit(l)}, ${lit(q[l])})`).join(',\n')}
) as v(locale, text)
on conflict (question_id, locale) do nothing;

`;
}

writeFileSync(join(root, 'supabase', 'seed.sql'), sql);
console.log(`Wrote supabase/seed.sql with ${data.questions.length} questions.`);
